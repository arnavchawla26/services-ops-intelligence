"""Weekly parts demand forecast with a rolling-origin backtest.

Demand = units of each part consumed per ISO week per region, from
dispatch_part joined to dispatch, case, installed_asset and site (the site's
region is where the part was consumed; the generator assigns technicians from
the same region, so the two agree). Weeks are Monday-start.

The generated quarter holds 13 usable weeks (2026-03-30 to 2026-06-22; the
first is the ramp-up as cases start, the week of 2026-06-29 is cut off by the
end of telemetry), so the forecast is WEEKLY with horizon 1 and a
rolling-origin backtest over the last 6 weeks: for each origin week o the
models see demand up to and including o and forecast o + 1. There are no
seasons in 13 weeks, so seasonal naive is not possible.

Models, all per series (region, part):
    naive       last week's demand
    ma4         mean of the last 4 weeks
    ses         simple exponential smoothing; alpha chosen per origin on the
                history before the origin (one-step error), never on the target
    lgbm        one pooled LightGBM over all series with lag 1..4, 4-week mean,
                region and part as features, trained on rows whose target is
                at or before the origin

Metrics: MAE and bias (mean of forecast - actual) per model, overall, by part,
by region, and for the fleet total per part (series summed over regions).

This demand is generated by sois.generate_enterprise from real failure dates
plus random background cases; the backtest proves the pipeline and the
comparison method, not the demand. A year of real dispatches would change
every number here.

Outputs: reports/parts_forecast_backtest.csv (per model, per level, MAE and
bias), reports/parts_forecast_detail.csv (per series, origin, model forecast
and actual, for the dashboard), reports/parts_forecast.png.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

MODELS = ("naive", "ma4", "ses", "lgbm")


# ---------------------------------------------------------------- demand table
def weekly_demand(enterprise: Path) -> pd.DataFrame:
    d = pd.read_csv(enterprise / "dispatch.csv", usecols=["dispatch_id", "case_id", "scheduled_at"])
    dp = pd.read_csv(enterprise / "dispatch_part.csv")
    c = pd.read_csv(enterprise / "case.csv", usecols=["case_id", "asset_id"])
    a = pd.read_csv(enterprise / "installed_asset.csv", usecols=["asset_id", "site_id"])
    s = pd.read_csv(enterprise / "site.csv", usecols=["site_id", "region"])
    x = dp.merge(d, on="dispatch_id").merge(c, on="case_id").merge(a, on="asset_id").merge(s, on="site_id")
    ts = pd.to_datetime(x["scheduled_at"])
    x["week"] = (ts - pd.to_timedelta(ts.dt.weekday, unit="D")).dt.normalize()
    dem = x.groupby(["week", "region", "part_id"], as_index=False)["quantity"].sum().rename(columns={"quantity": "demand"})
    return dem


def complete_grid(dem: pd.DataFrame, week_start: pd.Timestamp, week_end: pd.Timestamp) -> pd.DataFrame:
    """Every (week, region, part) in the window, zero-filled."""
    weeks = pd.date_range(week_start, week_end, freq="7D")
    regions = sorted(dem["region"].unique())
    parts = sorted(dem["part_id"].unique())
    grid = pd.MultiIndex.from_product([weeks, regions, parts], names=["week", "region", "part_id"]).to_frame(index=False)
    out = grid.merge(dem, on=["week", "region", "part_id"], how="left").fillna({"demand": 0})
    out["demand"] = out["demand"].astype(float)
    return out.sort_values(["region", "part_id", "week"]).reset_index(drop=True)


# ---------------------------------------------------------------- models
def ses_fit_alpha(y: np.ndarray, grid: np.ndarray = np.linspace(0.05, 0.95, 19)) -> float:
    """alpha minimising one-step-ahead squared error on y (all in the past)."""
    best, best_err = 0.5, np.inf
    for a in grid:
        level, err = y[0], 0.0
        for v in y[1:]:
            err += (level - v) ** 2
            level = a * v + (1 - a) * level
        if err < best_err:
            best, best_err = a, err
    return float(best)


def ses_forecast(y: np.ndarray, alpha: float) -> float:
    level = y[0]
    for v in y[1:]:
        level = alpha * v + (1 - alpha) * level
    return float(level)


def _lag_frame(grid: pd.DataFrame, n_lags: int = 4) -> pd.DataFrame:
    g = grid.copy()
    key = ["region", "part_id"]
    for k in range(1, n_lags + 1):
        g[f"lag{k}"] = g.groupby(key)["demand"].shift(k)
    g["ma4"] = g[[f"lag{k}" for k in range(1, 5)]].mean(axis=1)
    g["region_c"] = g["region"].astype("category")
    g["part_c"] = g["part_id"].astype("category")
    return g


def backtest(grid: pd.DataFrame, n_origins: int = 6, seed: int = 20261017) -> pd.DataFrame:
    """Rolling origin, horizon 1. Returns one row per (series, origin, model) with forecast and actual."""
    import lightgbm as lgb

    weeks = sorted(grid["week"].unique())
    origins = weeks[-n_origins - 1:-1]          # forecast target = origin + 1 week, last target = last week
    lagged = _lag_frame(grid)
    feats = ["lag1", "lag2", "lag3", "lag4", "ma4", "region_c", "part_c"]
    rows = []
    for o in origins:
        target_week = weeks[weeks.index(o) + 1]
        hist = grid[grid["week"] <= o]
        tgt = grid[grid["week"] == target_week].set_index(["region", "part_id"])["demand"]
        # pooled LightGBM on rows whose target week <= origin (features are lags, so no future leaks in)
        train = lagged[(lagged["week"] <= o) & lagged["lag4"].notna()]
        params = {"objective": "regression_l1", "learning_rate": 0.05, "num_leaves": 15, "min_data_in_leaf": 20,
                  "verbose": -1, "seed": seed, "num_threads": 4}
        booster = None
        if len(train) >= 50:
            booster = lgb.train(params, lgb.Dataset(train[feats], label=train["demand"], categorical_feature=["region_c", "part_c"]),
                                num_boost_round=200)
        pred_rows = lagged[lagged["week"] == target_week].set_index(["region", "part_id"])
        for (region, part), h in hist.groupby(["region", "part_id"]):
            y = h.sort_values("week")["demand"].to_numpy()
            actual = float(tgt.get((region, part), 0.0))
            f = {"naive": float(y[-1]), "ma4": float(y[-4:].mean())}
            alpha = ses_fit_alpha(y[:-1]) if len(y) > 2 else 0.5
            f["ses"] = ses_forecast(y, alpha)
            if booster is not None:
                f["lgbm"] = float(max(0.0, booster.predict(pred_rows.loc[[(region, part)], feats])[0]))
            else:
                f["lgbm"] = f["ma4"]
            for m, v in f.items():
                rows.append({"region": region, "part_id": part, "origin": o, "target_week": target_week,
                             "model": m, "forecast": round(v, 4), "actual": actual})
    return pd.DataFrame(rows)


def summarise(detail: pd.DataFrame) -> pd.DataFrame:
    d = detail.copy()
    d["err"] = d["forecast"] - d["actual"]
    d["abs_err"] = d["err"].abs()
    out = []

    def agg(frame: pd.DataFrame, level: str, key: str) -> None:
        g = frame.groupby(["model"] + ([key] if key else []), as_index=False).agg(
            n=("err", "size"), mae=("abs_err", "mean"), bias=("err", "mean"), mean_actual=("actual", "mean"))
        g.insert(0, "level", level)
        if not key:
            g.insert(2, "key", "all")
        else:
            g = g.rename(columns={key: "key"})
        out.append(g)

    agg(d, "region_part", "")
    agg(d, "by_part", "part_id")
    agg(d, "by_region", "region")
    tot = d.groupby(["model", "part_id", "origin"], as_index=False)[["forecast", "actual"]].sum()
    tot["err"] = tot["forecast"] - tot["actual"]
    tot["abs_err"] = tot["err"].abs()
    agg(tot, "fleet_total_by_part", "part_id")
    agg(tot, "fleet_total", "")
    res = pd.concat(out, ignore_index=True)
    res[["mae", "bias", "mean_actual"]] = res[["mae", "bias", "mean_actual"]].round(4)
    return res


def plot(detail: pd.DataFrame, grid: pd.DataFrame, path: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    weekly_total = grid.groupby("week")["demand"].sum()
    fc = detail.groupby(["model", "target_week"])["forecast"].sum().unstack(0)
    fig, ax = plt.subplots(figsize=(7.5, 4.2), dpi=130)
    ax.plot(weekly_total.index, weekly_total.values, color="#222", marker="o", label="actual (all regions, all parts)")
    styles = {"naive": ("#8a8a8a", "--"), "ma4": ("#3b6ea5", "-."), "ses": ("#6a994e", ":"), "lgbm": ("#b5452b", "-")}
    for m in MODELS:
        if m in fc:
            c, ls = styles[m]
            ax.plot(fc.index, fc[m].values, ls, color=c, marker="x", label=f"{m} (sum of series forecasts)")
    ax.set_ylabel("parts per week")
    ax.set_title("Weekly parts demand, rolling-origin backtest (generated dispatches)", fontsize=10)
    ax.grid(alpha=0.3)
    ax.legend(frameon=False, fontsize=8)
    fig.autofmt_xdate()
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def run(enterprise: Path, reports: Path, week_start: str = "2026-03-30", week_end: str = "2026-06-22",
        n_origins: int = 6, seed: int = 20261017) -> dict:
    reports.mkdir(parents=True, exist_ok=True)
    dem = weekly_demand(enterprise)
    grid = complete_grid(dem, pd.Timestamp(week_start), pd.Timestamp(week_end))
    detail = backtest(grid, n_origins, seed)
    summary = summarise(detail)
    summary.to_csv(reports / "parts_forecast_backtest.csv", index=False)
    detail.to_csv(reports / "parts_forecast_detail.csv", index=False)
    grid.to_csv(reports / "parts_weekly_demand.csv", index=False)
    plot(detail, grid, reports / "parts_forecast.png")
    overall = summary[summary["level"] == "region_part"].set_index("model")
    fleet = summary[summary["level"] == "fleet_total"].set_index("model")
    info = {
        "weeks": int(grid["week"].nunique()), "series": int(grid.groupby(["region", "part_id"]).ngroups),
        "origins": n_origins, "horizon_weeks": 1,
        "region_part_mae": {m: float(overall.loc[m, "mae"]) for m in MODELS},
        "region_part_bias": {m: float(overall.loc[m, "bias"]) for m in MODELS},
        "fleet_total_mae": {m: float(fleet.loc[m, "mae"]) for m in MODELS},
        "fleet_total_bias": {m: float(fleet.loc[m, "bias"]) for m in MODELS},
        "mean_weekly_demand_per_series": float(overall["mean_actual"].iloc[0]),
    }
    (reports / "parts_forecast_summary.json").write_text(json.dumps(info, indent=2) + "\n")
    return info


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--enterprise", type=Path, default=Path("data/enterprise"))
    ap.add_argument("--reports", type=Path, default=Path("reports"))
    ap.add_argument("--week-start", default="2026-03-30")
    ap.add_argument("--week-end", default="2026-06-22")
    ap.add_argument("--origins", type=int, default=6)
    args = ap.parse_args(argv)
    info = run(args.enterprise, args.reports, args.week_start, args.week_end, args.origins)
    print(json.dumps(info, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
