"""Case-deflection candidates: cases whose description matches a runbook.

A case is a deflection candidate when the text of its description is close
enough to a runbook (title + symptoms + steps) that a customer could have
followed the runbook instead of opening the case. Two scorers, run
independently so neither depends on the other:

    tfidf   TF-IDF (unigrams and bigrams, sublinear tf, fit on runbooks plus
            case descriptions) and cosine similarity (scikit-learn).
    bm25    Okapi BM25 (k1 = 1.5, b = 0.75) over the runbook corpus, own
            implementation, query = the case description's tokens.

Only runbooks covering the case's product family are eligible (scope
"family"); a family with no runbook at all falls back to every runbook. The
"all" scope (every runbook eligible) is also scored so the cost of the
restriction is visible.

Evaluation against truth/case_truth.csv (`deflectable`). The cases are split
in two halves by a seeded coin. The threshold is the one that maximises F1 on
the tune half; precision, recall and F1 are then reported on the other half,
with a precision-recall table across thresholds on that half. The halves are
also swapped once as a stability check. A third row, `tfidf+severity`, adds
the case record's severity (candidate only when severity >= 3), a rule an
operation would set from policy, not learn.

What the score proves. Cases and runbooks are generated by
sois.generate_enterprise (docs/GENERATOR.md). The generator decides
`deflectable` first, from category (how_to / config / firmware at severity 3
or 4 with a matched runbook: 85%; false_alarm: 60%; everything else: 3%), and
only then copies one of the matched runbook's symptom phrases into the
description. Non-deflectable cases carry their category's stock symptom
phrase, which is also the first symptom phrase of a runbook in that category.
So the text tells a matcher whether a runbook covers the symptom, which is
the generator's precondition for deflectability, and nothing about the
severity gate or the coin flips that follow it. The ceiling for any text
matcher on this data is therefore well below perfect, and the numbers below
measure how close the matcher gets to that ceiling, not whether real cases
could be deflected. The runbook-hit rate (did the matcher's top runbook equal
the one the generator used) is the cleaner test of the matching itself.

Outputs: reports/case_deflection.csv (one row per case: best runbook and
score per scorer, half, candidate flags, truth), reports/case_deflection_pr_table.csv,
reports/case_deflection_metrics.json, reports/case_deflection.png.
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd

SPLIT_SEED = 20261017
TOKEN = re.compile(r"[a-z0-9]+")


def tokenize(text: str) -> list[str]:
    return TOKEN.findall(str(text).lower())


class BM25:
    """Okapi BM25 over a small fixed corpus; scores every document for a query at once."""

    def __init__(self, docs: list[list[str]], k1: float = 1.5, b: float = 0.75) -> None:
        self.vocab: dict[str, int] = {}
        for d in docs:
            for t in d:
                self.vocab.setdefault(t, len(self.vocab))
        n_docs, v = len(docs), len(self.vocab)
        tf = np.zeros((n_docs, v))
        for i, d in enumerate(docs):
            for t in d:
                tf[i, self.vocab[t]] += 1
        dl = tf.sum(axis=1)
        avgdl = dl.mean() if n_docs else 1.0
        df = (tf > 0).sum(axis=0)
        idf = np.log(1.0 + (n_docs - df + 0.5) / (df + 0.5))
        denom = tf + k1 * (1.0 - b + b * dl[:, None] / avgdl)
        self.weights = idf[None, :] * tf * (k1 + 1.0) / np.where(denom == 0, 1.0, denom)

    def score(self, query: list[str]) -> np.ndarray:
        idx = sorted({self.vocab[t] for t in query if t in self.vocab})
        if not idx:
            return np.zeros(self.weights.shape[0])
        return self.weights[:, idx].sum(axis=1)


def runbook_text(rb: pd.DataFrame) -> list[str]:
    return (rb["title"].fillna("") + ". " + rb["symptoms"].fillna("") + ". " + rb["steps"].fillna("")).tolist()


def load(enterprise: Path, truth: Path | None) -> tuple[pd.DataFrame, pd.DataFrame]:
    c = pd.read_csv(enterprise / "case.csv", usecols=["case_id", "asset_id", "category", "severity", "description"], dtype=str)
    a = pd.read_csv(enterprise / "installed_asset.csv", usecols=["asset_id", "product_id"], dtype=str)
    p = pd.read_csv(enterprise / "product.csv", usecols=["product_id", "family"], dtype=str)
    rb = pd.read_csv(enterprise / "runbook.csv", dtype=str)
    x = c.merge(a, on="asset_id", how="left").merge(p, on="product_id", how="left")
    x["severity"] = pd.to_numeric(x["severity"], errors="coerce")
    x["description"] = x["description"].fillna("")
    if truth is not None and (truth / "case_truth.csv").exists():
        t = pd.read_csv(truth / "case_truth.csv", usecols=["case_id", "deflectable", "matching_runbook_id"], dtype=str)
        t["truth_deflectable"] = t["deflectable"].str.lower() == "true"
        x = x.merge(t[["case_id", "truth_deflectable", "matching_runbook_id"]], on="case_id", how="left")
    else:
        x["truth_deflectable"] = np.nan
        x["matching_runbook_id"] = None
    return x.reset_index(drop=True), rb.reset_index(drop=True)


def eligible_mask(case_family: pd.Series, rb_family: pd.Series) -> np.ndarray:
    """cases x runbooks boolean: same family; a family with no runbook gets every runbook."""
    fam_rb = rb_family.fillna("").to_numpy()
    fam_case = case_family.fillna("").to_numpy()
    m = fam_case[:, None] == fam_rb[None, :]
    none = ~m.any(axis=1)
    m[none, :] = True
    return m


def score_cases(x: pd.DataFrame, rb: pd.DataFrame) -> pd.DataFrame:
    """Adds best runbook and score per scorer and scope to a copy of x."""
    from sklearn.feature_extraction.text import TfidfVectorizer

    docs = runbook_text(rb)
    queries = x["description"].tolist()
    vec = TfidfVectorizer(tokenizer=tokenize, token_pattern=None, ngram_range=(1, 2), sublinear_tf=True, lowercase=False)
    vec.fit(docs + queries)
    sims = (vec.transform(queries) @ vec.transform(docs).T).toarray()          # cosine: rows are l2-normalised
    bm = BM25([tokenize(d) for d in docs])
    bm_scores = np.vstack([bm.score(tokenize(q)) for q in queries]) if queries else np.zeros((0, len(docs)))

    out = x.copy()
    masks = {"family": eligible_mask(x["family"], rb["product_family"]), "all": np.ones(sims.shape, dtype=bool)}
    ids = rb["runbook_id"].to_numpy()
    for scorer, mat in (("tfidf", sims), ("bm25", bm_scores)):
        for scope, m in masks.items():
            masked = np.where(m, mat, -np.inf)
            best = masked.argmax(axis=1)
            suffix = "" if scope == "family" else "_all"
            out[f"{scorer}_runbook{suffix}"] = ids[best]
            out[f"{scorer}_score{suffix}"] = np.round(masked[np.arange(len(best)), best], 4)
    return out


def assign_halves(case_ids: pd.Series, seed: int = SPLIT_SEED) -> pd.Series:
    rng = np.random.default_rng(seed)
    return pd.Series(np.where(rng.random(len(case_ids)) < 0.5, "tune", "report"), index=case_ids.index)


def prf(flag: np.ndarray, truth: np.ndarray) -> dict:
    tp = int((flag & truth).sum())
    fp = int((flag & ~truth).sum())
    fn = int((~flag & truth).sum())
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return {"flagged": tp + fp, "tp": tp, "fp": fp, "fn": fn,
            "precision": round(precision, 4), "recall": round(recall, 4), "f1": round(f1, 4)}


def choose_threshold(score: np.ndarray, truth: np.ndarray, extra: np.ndarray | None = None) -> float:
    """Threshold maximising F1 on (score, truth); ties go to the higher threshold."""
    grid = np.unique(score)
    if len(grid) > 400:
        grid = np.unique(np.quantile(score, np.linspace(0, 1, 401)))
    best_t, best_f1 = float(grid[-1]) if len(grid) else 0.0, -1.0
    for t in grid:
        flag = score >= t
        if extra is not None:
            flag &= extra
        f1 = prf(flag, truth)["f1"]
        if f1 >= best_f1:
            best_t, best_f1 = float(t), f1
    return best_t


def pr_table(score: np.ndarray, truth: np.ndarray, chosen: float, scorer: str) -> pd.DataFrame:
    grid = sorted(set(np.round(np.quantile(score, np.linspace(0.05, 0.95, 19)), 4)) | {round(chosen, 4)})
    rows = []
    for t in grid:
        r = prf(score >= t, truth)
        rows.append({"scorer": scorer, "threshold": t, "chosen": math.isclose(t, round(chosen, 4)),
                     "flagged_share": round(float((score >= t).mean()), 4), **r})
    return pd.DataFrame(rows)


def evaluate(scored: pd.DataFrame) -> tuple[dict, pd.DataFrame, pd.DataFrame]:
    """Threshold on the tune half, numbers on the report half. Returns (metrics, pr_table, by_category)."""
    truth_all = scored["truth_deflectable"].astype(bool).to_numpy()
    half = scored["half"].to_numpy()
    sev_ok = (scored["severity"].fillna(0) >= 3).to_numpy()
    variants = {
        "tfidf": ("tfidf_score", None), "bm25": ("bm25_score", None),
        "tfidf_all_runbooks": ("tfidf_score_all", None), "bm25_all_runbooks": ("bm25_score_all", None),
        "tfidf+severity": ("tfidf_score", sev_ok),
    }
    metrics: dict = {"variants": {}}
    tables, cats = [], []
    for name, (col, extra) in variants.items():
        s = scored[col].to_numpy(dtype=float)
        res = {}
        for tune, rep in (("tune", "report"), ("report", "tune")):
            ti, ri = half == tune, half == rep
            t = choose_threshold(s[ti], truth_all[ti], None if extra is None else extra[ti])
            flag = s[ri] >= t
            if extra is not None:
                flag &= extra[ri]
            r = prf(flag, truth_all[ri])
            res[f"threshold_on_{tune}"] = {"threshold": round(t, 4), "evaluated_on": rep, "cases": int(ri.sum()),
                                          "deflectable": int(truth_all[ri].sum()), **r}
        metrics["variants"][name] = res
        # the headline direction: threshold chosen on tune, reported on report
        t = res["threshold_on_tune"]["threshold"]
        ri = half == "report"
        if extra is None:
            tables.append(pr_table(s[ri], truth_all[ri], t, name))
        if name in ("tfidf", "bm25", "tfidf+severity"):
            flag = s >= t
            if extra is not None:
                flag &= extra
            scored[f"{name.replace('+', '_')}_candidate"] = flag
            rep = scored[ri].assign(flag=flag[ri])
            for cat, g in rep.groupby("category"):
                r = prf(g["flag"].to_numpy(), g["truth_deflectable"].astype(bool).to_numpy())
                cats.append({"scorer": name, "category": cat, "cases": int(len(g)), "deflectable": int(g["truth_deflectable"].astype(bool).sum()), **r})
    # runbook hit rate: deflectable cases that have a matching runbook in truth, report half
    ri = half == "report"
    has_rb = scored["matching_runbook_id"].notna() & scored["truth_deflectable"].astype(bool) & ri
    metrics["runbook_hit_rate_report_half"] = {
        "cases": int(has_rb.sum()),
        "tfidf": round(float((scored.loc[has_rb, "tfidf_runbook"] == scored.loc[has_rb, "matching_runbook_id"]).mean()), 4) if has_rb.any() else None,
        "bm25": round(float((scored.loc[has_rb, "bm25_runbook"] == scored.loc[has_rb, "matching_runbook_id"]).mean()), 4) if has_rb.any() else None,
        "tfidf_all_runbooks": round(float((scored.loc[has_rb, "tfidf_runbook_all"] == scored.loc[has_rb, "matching_runbook_id"]).mean()), 4) if has_rb.any() else None,
        "bm25_all_runbooks": round(float((scored.loc[has_rb, "bm25_runbook_all"] == scored.loc[has_rb, "matching_runbook_id"]).mean()), 4) if has_rb.any() else None,
        "note": "share of truly deflectable cases (with a runbook in truth) whose top-scoring runbook is the generator's; "
                "'family' scope can only hit when the generator stayed in the family",
    }
    return metrics, pd.concat(tables, ignore_index=True), pd.DataFrame(cats)


def plot(table: pd.DataFrame, cats: pd.DataFrame, path: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, 2, figsize=(10, 4.2), dpi=130)
    ax = axes[0]
    for scorer, color in (("tfidf", "#3b6ea5"), ("bm25", "#b5452b")):
        g = table[table["scorer"] == scorer].sort_values("recall")
        ax.plot(g["recall"], g["precision"], marker="o", ms=3, color=color, label=scorer)
        ch = g[g["chosen"]]
        if len(ch):
            ax.scatter(ch["recall"], ch["precision"], s=90, facecolors="none", edgecolors=color, linewidths=1.5)
    ax.set_xlabel("recall of truth-deflectable cases")
    ax.set_ylabel("precision of flagged cases")
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.grid(alpha=0.3)
    ax.legend(frameon=False, fontsize=8)
    ax.set_title("Precision-recall across thresholds (report half; circle = threshold chosen on tune half)", fontsize=8.5)
    ax = axes[1]
    g = cats[cats["scorer"] == "tfidf"].sort_values("cases")
    if len(g):
        y = np.arange(len(g))
        ax.barh(y - 0.2, g["recall"], height=0.4, color="#3b6ea5", label="recall")
        ax.barh(y + 0.2, g["precision"], height=0.4, color="#7f9fc4", label="precision")
        ax.set_yticks(y)
        ax.set_yticklabels(g["category"], fontsize=8)
        ax.set_xlim(0, 1)
        ax.legend(frameon=False, fontsize=8, loc="lower right")
        ax.grid(axis="x", alpha=0.3)
    ax.set_title("TF-IDF at the chosen threshold, by case category", fontsize=8.5)
    fig.suptitle("Generated cases and runbooks: the matcher recovers whether a runbook covers the symptom, "
                 "not the generator's severity gate or coin flips", fontsize=8, color="#555")
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def run(enterprise: Path, truth: Path | None, reports: Path, seed: int = SPLIT_SEED) -> dict:
    reports.mkdir(parents=True, exist_ok=True)
    x, rb = load(enterprise, truth)
    scored = score_cases(x, rb)
    scored["half"] = assign_halves(scored["case_id"], seed)
    info: dict = {
        "cases": int(len(scored)), "runbooks": int(len(rb)),
        "cases_whose_family_has_no_runbook_so_all_are_eligible": int((~x["family"].isin(rb["product_family"])).sum()),
        "split": {"seed": seed, "tune": int((scored["half"] == "tune").sum()), "report": int((scored["half"] == "report").sum())},
        "scorers": {"tfidf": "TF-IDF unigrams+bigrams, sublinear tf, cosine; fit on runbooks + case descriptions",
                    "bm25": "Okapi BM25 k1=1.5 b=0.75 over runbook title+symptoms+steps"},
        "scope": "family: only runbooks of the case's product family are eligible; a family with no runbook falls back to all",
    }
    has_truth = scored["truth_deflectable"].notna().any()
    if has_truth:
        scored["truth_deflectable"] = scored["truth_deflectable"].astype(bool)
        info["deflectable_in_truth"] = int(scored["truth_deflectable"].sum())
        metrics, table, cats = evaluate(scored)
        info.update(metrics)
        info["by_category_report_half"] = cats.to_dict(orient="records")
        table.to_csv(reports / "case_deflection_pr_table.csv", index=False)
        plot(table, cats, reports / "case_deflection.png")
        info["caveat"] = (
            "Cases and runbooks are generated (docs/GENERATOR.md). The generator sets `deflectable` from category, "
            "severity and coin flips, then copies a runbook phrase into deflectable descriptions; non-deflectable cases "
            "carry a stock phrase that is also a runbook's first symptom. Text matching therefore recovers the "
            "'a runbook covers this symptom' precondition and cannot see the severity gate or the coins. These numbers "
            "measure the matcher against that ceiling, not whether any real case could have been deflected."
        )
    cols = ["case_id", "category", "severity", "family", "half",
            "tfidf_runbook", "tfidf_score", "bm25_runbook", "bm25_score",
            "tfidf_runbook_all", "tfidf_score_all", "bm25_runbook_all", "bm25_score_all"]
    cols += [c for c in ("tfidf_candidate", "bm25_candidate", "tfidf_severity_candidate", "truth_deflectable", "matching_runbook_id") if c in scored.columns]
    scored[cols].to_csv(reports / "case_deflection.csv", index=False)
    (reports / "case_deflection_metrics.json").write_text(json.dumps(info, indent=2) + "\n")
    return info


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--enterprise", type=Path, default=Path("data/enterprise"))
    ap.add_argument("--truth", type=Path, default=Path("truth"))
    ap.add_argument("--reports", type=Path, default=Path("reports"))
    ap.add_argument("--seed", type=int, default=SPLIT_SEED)
    args = ap.parse_args(argv)
    info = run(args.enterprise, args.truth if args.truth.exists() else None, args.reports, args.seed)
    headline = {k: v for k, v in info.items() if k not in ("by_category_report_half",)}
    print(json.dumps(headline, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
