"""Repeat-dispatch analysis over the generated support tables.

Definition. A dispatch is a repeat when either
    same_case   it is visit 2 or 3 on a case that already had a truck
                (dispatch.visit_number > 1), or
    cross_case  it is the first visit of a case on an asset whose previous case
                (one that itself had a dispatch) closed within the 30 days
                before this visit was scheduled.
The two are reported separately and together. The rate is repeats divided by
all dispatches in the group.

Case timestamps come in two formats (MESS_RULES D1); they are parsed here from
case.csv, not taken from truth/, so the analysis sees the data the way a
support system would hand it over. truth/dispatch_truth.csv is used only to
check the answer: its `necessary` flag says whether the truck was needed
(a real hardware fault, or a repeat after parts_not_available / incomplete on a
real fault), so the comparison splits repeats into necessary and avoidable.

Grouping: product family, case category, site region, technician, and the
preferred supplier of the drive sled or other part used on the FIRST visit of
the case (the part a repeat follows).

Caveat: cases, dispatches and outcomes are generated by sois.generate_enterprise
with the probabilities in docs/GENERATOR.md (first-visit outcomes resolved 72%,
unresolved visits followed by another 85% of the time, 6% of resolved ones
followed anyway). The rates below reproduce those rules; they say nothing
about any real service operation. The code and the definition are the point.

Outputs: reports/repeat_dispatch.csv (one row per dimension value),
reports/repeat_dispatch_summary.json, reports/repeat_dispatch.png.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

CROSS_CASE_WINDOW_DAYS = 30


def parse_mixed_timestamp(s: pd.Series) -> pd.Series:
    """ISO 8601 ('2026-04-02T12:11:06') or US 'MM/DD/YYYY HH:MM' (legacy_crm), else NaT."""
    s = s.astype("string")
    iso = pd.to_datetime(s, format="%Y-%m-%dT%H:%M:%S", errors="coerce")
    us = pd.to_datetime(s, format="%m/%d/%Y %H:%M", errors="coerce")
    return iso.fillna(us)


def load(enterprise: Path, truth: Path | None) -> pd.DataFrame:
    d = pd.read_csv(enterprise / "dispatch.csv")
    c = pd.read_csv(enterprise / "case.csv", usecols=["case_id", "opened_at", "closed_at", "asset_id", "category", "severity"], dtype=str)
    a = pd.read_csv(enterprise / "installed_asset.csv", usecols=["asset_id", "site_id", "product_id"])
    p = pd.read_csv(enterprise / "product.csv", usecols=["product_id", "family"])
    s = pd.read_csv(enterprise / "site.csv", usecols=["site_id", "region"])
    t = pd.read_csv(enterprise / "technician.csv", usecols=["technician_id", "name"]).rename(columns={"name": "technician"})
    dp = pd.read_csv(enterprise / "dispatch_part.csv")
    ps = pd.read_csv(enterprise / "part_supplier.csv")
    sup = pd.read_csv(enterprise / "supplier.csv", usecols=["supplier_id", "name"]).rename(columns={"name": "supplier"})

    c["opened"] = parse_mixed_timestamp(c["opened_at"])
    c["closed"] = parse_mixed_timestamp(c["closed_at"])
    x = (d.merge(c[["case_id", "asset_id", "category", "severity", "opened", "closed"]], on="case_id", how="left")
          .merge(a, on="asset_id", how="left").merge(p, on="product_id", how="left")
          .merge(s, on="site_id", how="left").merge(t, on="technician_id", how="left"))
    x["scheduled"] = pd.to_datetime(x["scheduled_at"])

    # supplier of the part used on the first visit of the case (preferred supplier of that part)
    pref = ps[ps["preferred"].astype(str).str.lower() == "true"][["part_id", "supplier_id"]].merge(sup, on="supplier_id")
    first_parts = dp.merge(d[d["visit_number"] == 1][["dispatch_id", "case_id"]], on="dispatch_id").merge(pref, on="part_id", how="left")
    first_sup = first_parts.sort_values("part_id").drop_duplicates("case_id")[["case_id", "supplier"]]
    x = x.merge(first_sup, on="case_id", how="left")
    x["supplier"] = x["supplier"].fillna("no part used")

    x["same_case_repeat"] = x["visit_number"] > 1
    x["cross_case_repeat"] = cross_case_repeats(x)
    x["is_repeat"] = x["same_case_repeat"] | x["cross_case_repeat"]

    if truth is not None and (truth / "dispatch_truth.csv").exists():
        tr = pd.read_csv(truth / "dispatch_truth.csv", usecols=["dispatch_id", "necessary", "is_repeat", "reason"])
        tr["necessary"] = tr["necessary"].astype(str).str.lower() == "true"
        tr["truth_is_repeat"] = tr["is_repeat"].astype(str).str.lower() == "true"
        x = x.merge(tr[["dispatch_id", "necessary", "truth_is_repeat", "reason"]], on="dispatch_id", how="left")
    else:
        x["necessary"] = np.nan
        x["truth_is_repeat"] = np.nan
        x["reason"] = None
    return x


def cross_case_repeats(x: pd.DataFrame, window_days: int = CROSS_CASE_WINDOW_DAYS) -> pd.Series:
    """First visits whose asset had another dispatched case close within window_days before."""
    first = x[x["visit_number"] == 1][["dispatch_id", "asset_id", "case_id", "scheduled"]]
    closed = x[["asset_id", "case_id", "closed"]].dropna(subset=["closed"]).drop_duplicates(["asset_id", "case_id"])
    m = first.merge(closed, on="asset_id", suffixes=("", "_prev"))
    m = m[(m["case_id"] != m["case_id_prev"])
          & (m["closed"] <= m["scheduled"])
          & (m["scheduled"] - m["closed"] <= pd.Timedelta(days=window_days))]
    flagged = set(m["dispatch_id"])
    return x["dispatch_id"].isin(flagged)


def rates(x: pd.DataFrame) -> pd.DataFrame:
    dims = {"product_family": "family", "case_category": "category", "region": "region",
            "technician": "technician", "first_visit_part_supplier": "supplier"}
    has_truth = x["necessary"].notna().any()
    out = []
    for dim, col in [("all", None)] + list(dims.items()):
        groups = [("all", x)] if col is None else list(x.groupby(col, dropna=False))
        for key, g in groups:
            rep = g[g["is_repeat"]]
            row = {
                "dimension": dim, "key": str(key), "dispatches": int(len(g)),
                "repeats": int(len(rep)), "same_case_repeats": int(g["same_case_repeat"].sum()),
                "cross_case_repeats": int(g["cross_case_repeat"].sum()),
                "repeat_rate": round(len(rep) / max(1, len(g)), 4),
            }
            if has_truth:
                nec = rep["necessary"].fillna(False).astype(bool)
                row["repeats_necessary"] = int(nec.sum())
                row["repeats_avoidable"] = int((~nec).sum())
                row["avoidable_repeat_rate"] = round(int((~nec).sum()) / max(1, len(g)), 4)
                row["first_visits_unnecessary"] = int((~g[g["visit_number"] == 1]["necessary"].fillna(False).astype(bool)).sum())
            out.append(row)
    return pd.DataFrame(out).sort_values(["dimension", "dispatches"], ascending=[True, False]).reset_index(drop=True)


def plot(table: pd.DataFrame, path: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    has_truth = "repeats_avoidable" in table.columns
    fig, axes = plt.subplots(1, 2, figsize=(9.5, 4.2), dpi=130)
    for ax, dim, title in zip(axes, ("case_category", "product_family"), ("by case category", "by product family")):
        g = table[table["dimension"] == dim].sort_values("repeat_rate")
        if has_truth:
            nec = g["repeats_necessary"] / g["dispatches"]
            avo = g["repeats_avoidable"] / g["dispatches"]
            ax.barh(g["key"], nec, color="#3b6ea5", label="necessary repeat")
            ax.barh(g["key"], avo, left=nec, color="#b5452b", label="avoidable repeat")
        else:
            ax.barh(g["key"], g["repeat_rate"], color="#3b6ea5")
        ax.set_xlabel("share of dispatches that are repeats")
        ax.set_title(f"Repeat dispatches {title}", fontsize=10)
        ax.grid(axis="x", alpha=0.3)
    if has_truth:
        axes[0].legend(frameon=False, fontsize=8, loc="lower right")
    fig.suptitle("Generated support data: rates reproduce the generator's rules, not a real operation", fontsize=8, color="#555")
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def run(enterprise: Path, truth: Path | None, reports: Path) -> dict:
    reports.mkdir(parents=True, exist_ok=True)
    x = load(enterprise, truth)
    table = rates(x)
    table.to_csv(reports / "repeat_dispatch.csv", index=False)
    plot(table, reports / "repeat_dispatch.png")
    allrow = table[table["dimension"] == "all"].iloc[0]
    info = {
        "dispatches": int(allrow["dispatches"]), "repeats": int(allrow["repeats"]),
        "repeat_rate": float(allrow["repeat_rate"]),
        "same_case_repeats": int(allrow["same_case_repeats"]), "cross_case_repeats": int(allrow["cross_case_repeats"]),
        "cross_case_window_days": CROSS_CASE_WINDOW_DAYS,
        "cases_with_dispatch": int(x["case_id"].nunique()),
        "unparsed_case_timestamps": int(x["opened"].isna().sum()),
    }
    if x["necessary"].notna().any():
        rep = x[x["is_repeat"]]
        info.update({
            "repeats_necessary": int(rep["necessary"].fillna(False).astype(bool).sum()),
            "repeats_avoidable": int((~rep["necessary"].fillna(False).astype(bool)).sum()),
            "same_case_definition_matches_truth": bool((x["same_case_repeat"] == x["truth_is_repeat"].fillna(False)).all()),
            "first_visits_unnecessary_share": round(float((~x.loc[x["visit_number"] == 1, "necessary"].fillna(False).astype(bool)).mean()), 4),
            "repeat_reasons": {str(k): int(v) for k, v in rep["reason"].value_counts(dropna=False).items()},
        })
    (reports / "repeat_dispatch_summary.json").write_text(json.dumps(info, indent=2) + "\n")
    return info


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--enterprise", type=Path, default=Path("data/enterprise"))
    ap.add_argument("--truth", type=Path, default=Path("truth"))
    ap.add_argument("--reports", type=Path, default=Path("reports"))
    args = ap.parse_args(argv)
    info = run(args.enterprise, args.truth if args.truth.exists() else None, args.reports)
    print(json.dumps(info, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
