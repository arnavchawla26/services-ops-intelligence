"""Services Ops Intelligence dashboard. Reads only small precomputed files under
reports/, so it runs without the telemetry or the enterprise tables.

    make dashboard      (uv run streamlit run app/dashboard.py)

Pages: Fleet risk, Dispatch budget, Parts, Repeat dispatch. Every number comes
from reports/*.csv|json written by sois.failure_model, sois.parts_forecast and
sois.repeat_dispatch; nothing is computed live.
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd
import streamlit as st

REPORTS = Path(__file__).resolve().parent.parent / "reports"


@st.cache_data
def load_csv(name: str) -> pd.DataFrame:
    return pd.read_csv(REPORTS / name)


@st.cache_data
def load_json(name: str) -> dict:
    return json.loads((REPORTS / name).read_text())


def need(*names: str) -> bool:
    missing = [n for n in names if not (REPORTS / n).exists()]
    if missing:
        st.warning("Missing under reports/: " + ", ".join(missing) + ". Run `make models` first.")
        return False
    return True


st.set_page_config(page_title="Services Ops Intelligence", layout="wide")
st.sidebar.title("Services Ops Intelligence")
page = st.sidebar.radio("Page", ["Fleet risk", "Dispatch budget", "Parts", "Repeat dispatch"], label_visibility="collapsed")
st.sidebar.caption(
    "Telemetry: Backblaze Hard Drive Data 2026 Q2 (real). Accounts, sites, cases, dispatches, parts: "
    "generated by sois.generate_enterprise and labelled as such. Failure model is evaluated on a test window "
    "whose labels were never seen in training."
)

if page == "Fleet risk":
    st.header("Fleet risk: 30-day failure probability, scored on the last telemetry day")
    if need("failure_model_metrics.json", "fleet_risk_sites.csv", "fleet_risk_top100.csv", "fleet_risk_vaults.csv"):
        m = load_json("failure_model_metrics.json")
        fs = m.get("fleet_scoring", {})
        c1, c2, c3, c4 = st.columns(4)
        c1.metric("Score date", fs.get("score_date", "n/a"))
        c2.metric("Drives scored", f"{fs.get('drives_scored', 0):,}")
        c3.metric("Expected failures, next 30 days", f"{fs.get('expected_failures_30d', 0):,.0f}")
        c4.metric("Test PR-AUC (LightGBM)", f"{m['test']['lightgbm']['pr_auc']:.3f}")
        st.caption(
            "Expected failures = sum of calibrated probabilities. Calibration was fit on about "
            f"{m['counts']['cal_positives']} events, so treat the total as a rough number, not a forecast."
        )
        left, right = st.columns(2)
        with left:
            st.subheader("Riskiest customer sites (generated enterprise layer)")
            sites = load_csv("fleet_risk_sites.csv")
            st.dataframe(sites.head(25)[["site_name", "account_name", "region", "drives", "expected_failures_30d", "max_p", "heuristic_flagged"]],
                         hide_index=True, use_container_width=True)
        with right:
            st.subheader("Riskiest vaults (real Backblaze datacenter / vault)")
            vaults = load_csv("fleet_risk_vaults.csv")
            st.dataframe(vaults.head(25), hide_index=True, use_container_width=True)
        st.subheader("100 riskiest drives with their site and account")
        top = load_csv("fleet_risk_top100.csv")
        cols = [c for c in ["serial_number", "model", "p_fail_30d", "site_name", "account_name", "region", "product_id",
                            "warranty_end", "smart_5_raw", "smart_187_raw", "smart_197_raw", "smart_198_raw", "smart_9_raw"] if c in top.columns]
        st.dataframe(top[cols], hide_index=True, use_container_width=True, height=500)

elif page == "Dispatch budget":
    st.header("Dispatch budget: trucks per day vs failures caught")
    if need("dispatch_budget_curve.csv", "dispatch_budget.csv", "failure_model_metrics.json"):
        m = load_json("failure_model_metrics.json")
        cfg, cnt = m["config"], m["counts"]
        st.caption(
            f"Test window: prediction dates {cfg['test_prediction_dates'][0]} to {cfg['test_prediction_dates'][1]}, "
            f"labels through {cfg['test_labels_through']}; {cnt['test_drive_days']:,} drive-days, "
            f"{cnt['test_positive_drive_days']:,} positive drive-days from {cnt['test_distinct_failing_drives']} distinct failing drives. "
            f"Training labels end {cfg['train_labels_through']}; no test label was ever a training label."
        )
        curve = load_csv("dispatch_budget_curve.csv")
        budget = st.slider("Trucks per day", 1, int(curve["daily_budget"].max()), 50)
        at = curve[curve["daily_budget"] == budget].set_index("model")
        cols = st.columns(3)
        for col, name in zip(cols, ["heuristic", "logistic", "lightgbm"]):
            if name in at.index:
                r = at.loc[name]
                col.metric(name, f"{r['caught_per_day']:.1f} caught / day",
                           f"{r['wasted_per_day']:.1f} trucks for nothing; recall {r['recall']:.1%}", delta_color="off")
        st.caption(f"About {curve['positives_per_day'].iloc[0]:.0f} drives per day are within 30 days of failing in this window.")
        pivot = curve.pivot(index="daily_budget", columns="model", values="caught_per_day")
        st.line_chart(pivot, x_label="trucks per day", y_label="failures caught per day")
        st.subheader("Fixed budgets")
        st.dataframe(load_csv("dispatch_budget.csv"), hide_index=True, use_container_width=True)
        st.subheader("Ranking quality on the test window")
        rows = []
        for name in ("heuristic", "logistic", "lightgbm"):
            t = m["test"][name]
            rows.append({"model": name, "PR-AUC": t["pr_auc"], "recall in top 0.1%": t["recall_top_0.001"],
                         "recall in top 1%": t["recall_top_0.01"], "Brier (calibrated)": t.get("brier_calibrated")})
        st.dataframe(pd.DataFrame(rows), hide_index=True, use_container_width=True)
        hf = m["test"]["heuristic_flag_set"]
        st.caption(
            f"Backblaze's rule (any of SMART 5/187/188/197/198 raw > 0) flags {hf['flagged_per_day']:,.0f} drives a day "
            f"({hf['flagged_share_of_drive_days']:.1%} of the fleet) and would catch {hf['recall_if_every_flagged_drive_dispatched']:.0%} "
            f"of the failures if every flagged drive got a truck; precision {hf['precision_of_flag']:.2%}."
        )
        st.subheader("Reliability (LightGBM, calibrated), deciles of predicted probability")
        st.dataframe(load_csv("reliability.csv"), hide_index=True, use_container_width=True)

elif page == "Parts":
    st.header("Parts demand: weekly forecast vs actual (generated dispatches)")
    if need("parts_forecast_backtest.csv", "parts_forecast_detail.csv", "parts_weekly_demand.csv", "parts_forecast_summary.json"):
        s = load_json("parts_forecast_summary.json")
        st.caption(
            f"{s['weeks']} weeks, {s['series']} region x part series, rolling-origin backtest over the last {s['origins']} weeks, "
            "horizon 1 week. The demand comes from the generated dispatch tables; the backtest proves the pipeline, not the demand."
        )
        back = load_csv("parts_forecast_backtest.csv")
        c1, c2 = st.columns(2)
        with c1:
            st.subheader("MAE and bias per model, region x part level")
            st.dataframe(back[back["level"] == "region_part"][["model", "n", "mae", "bias", "mean_actual"]], hide_index=True, use_container_width=True)
        with c2:
            st.subheader("MAE and bias per model, fleet total per part")
            st.dataframe(back[back["level"] == "fleet_total"][["model", "n", "mae", "bias", "mean_actual"]], hide_index=True, use_container_width=True)
        detail = load_csv("parts_forecast_detail.csv")
        dem = load_csv("parts_weekly_demand.csv")
        region = st.selectbox("Region", ["all"] + sorted(dem["region"].unique()))
        part = st.selectbox("Part", ["all"] + sorted(dem["part_id"].unique()))
        d, a = detail, dem
        if region != "all":
            d, a = d[d["region"] == region], a[a["region"] == region]
        if part != "all":
            d, a = d[d["part_id"] == part], a[a["part_id"] == part]
        actual = a.groupby("week")["demand"].sum().rename("actual")
        fc = d.groupby(["target_week", "model"])["forecast"].sum().unstack("model")
        fc.index.name = "week"
        chart = pd.concat([actual, fc], axis=1)
        chart.index = pd.to_datetime(chart.index)
        st.line_chart(chart.sort_index(), y_label="parts per week")
        st.subheader("By part (region x part level)")
        st.dataframe(back[back["level"] == "by_part"].pivot(index="key", columns="model", values="mae").round(3), use_container_width=True)

elif page == "Repeat dispatch":
    st.header("Repeat dispatches (generated support data)")
    if need("repeat_dispatch.csv", "repeat_dispatch_summary.json"):
        s = load_json("repeat_dispatch_summary.json")
        c1, c2, c3, c4 = st.columns(4)
        c1.metric("Dispatches", f"{s['dispatches']:,}")
        c2.metric("Repeat rate", f"{s['repeat_rate']:.1%}")
        c3.metric("Same-case / cross-case", f"{s['same_case_repeats']:,} / {s['cross_case_repeats']:,}")
        if "repeats_avoidable" in s:
            c4.metric("Avoidable repeats (per truth)", f"{s['repeats_avoidable']:,} of {s['repeats']:,}")
        st.caption(
            "Repeat = visit 2 or 3 on the same case, or a first visit within 30 days of a previous dispatched case closing on "
            "the same asset. 'Avoidable' uses truth/dispatch_truth.csv, which exists only because the data is generated; "
            "the rates reproduce the generator's rules (docs/GENERATOR.md), not a real operation."
        )
        tab = load_csv("repeat_dispatch.csv")
        dim = st.selectbox("Break down by", ["case_category", "product_family", "region", "first_visit_part_supplier", "technician"])
        g = tab[tab["dimension"] == dim].sort_values("repeat_rate", ascending=False)
        cols = [c for c in ["key", "dispatches", "repeats", "same_case_repeats", "cross_case_repeats", "repeat_rate",
                            "repeats_necessary", "repeats_avoidable", "avoidable_repeat_rate"] if c in g.columns]
        st.dataframe(g[cols], hide_index=True, use_container_width=True, height=min(600, 40 + 35 * len(g)))
        st.bar_chart(g.set_index("key")["repeat_rate"], y_label="repeat rate")
